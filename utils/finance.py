@st.cache_data(show_spinner=False)
def load() -> pd.DataFrame:
    df = pd.read_excel(PATH, dtype={"접수번호": str})
    df["영업이익률"] = df["영업이익_원"] / df["영업수익_원"] * 100
    df["순이익률"] = df["당기순이익_원"] / df["영업수익_원"] * 100
    df["영업현금흐름비율"] = df["영업활동현금흐름_원"] / df["영업수익_원"] * 100
    df["부채비율"] = (df["부채총계_원"] / df["자본총계_원"] * 100).where(df["자본총계_원"] > 0)
    df["ROA"] = df["당기순이익_원"] / df["자산총계_원"] * 100
    df["회사"] = pd.Categorical(df["회사"], categories=ORDER)
    return df.sort_values(["회사", "연도"]).reset_index(drop=True)


def eok(won: float) -> str:
    """원 → '3,638억 원' / 1조가 넘으면 '4.5조 원'."""
    return f"{won / 1e12:,.1f}조 원" if abs(won) >= 1e12 else f"{won / 1e8:,.0f}억 원"


def won100(v: float) -> str:
    """비율(%) → '6.4원' (매출 100원 중)."""
    return f"{v:.1f}원"
